import io
from html import escape
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer

def render_report(scan):
    output=io.BytesIO()
    styles=getSampleStyleSheet()
    styles.add(ParagraphStyle(name="BodySafe",fontName="Helvetica",fontSize=9,leading=13,spaceAfter=8,wordWrap="CJK"))
    styles["Title"].textColor=colors.HexColor("#163F43")
    story=[]
    def para(text,style="BodySafe"):
        # Untrusted evidence is text, never ReportLab XML.
        story.append(Paragraph(escape(str(text)).replace("\n","<br/>"),styles[style]))
    para("SENTINEL LAB", "Title")
    para("Static assessment report","Heading2")
    for label,value in [("File",scan.filename),("SHA-256",scan.sha256),("Size",f"{scan.size} bytes"),
                        ("Created",str(scan.created_at)+" UTC"),("Review status",scan.status),
                        ("Architecture",scan.static.get("architecture")),("Method",scan.static.get("method"))]:
        para(f"{label}: {value}")
    para("Scope and limitations","Heading2")
    para("Preliminary static risk assessment only. Uploaded code was not executed. No result guarantees safety. Local indicators, third-party reputation and supervised AI findings are separate evidence sources.")
    para("Local static inspection","Heading2")
    para(scan.static.get("limitations",""))
    for sec in scan.static.get("sections",[]):
        para(f"Section {sec['name']} | {sec['rva']} | {sec['permissions']} | {sec['size']} bytes | entropy {sec['entropy']}")
    findings=scan.static.get("indicators",[])
    if not findings:
        para("No obvious section-level indicators found. This is not a clean-file verdict.")
    for item in findings:
        para(item["title"]+" ["+item["severity"]+"]","Heading3")
        para(item["detail"])
        para("Evidence: "+item["evidence"])
    para("Third-party reputation","Heading2")
    reputation=scan.reputation or {}
    para("Provider: VirusTotal | status: "+reputation.get("status","not_requested"))
    para("Lookup time: "+str(reputation.get("queried_at","Not queried")))
    para("Provider analysis timestamp: "+str(reputation.get("analysis_date","Not available")))
    for name,count in reputation.get("stats",{}).items():
        para(f"{name}: {count}")
    para("Supervised OpenBin findings","Heading2")
    if scan.reviewed_data is None:
        para("Awaiting supervised review/import. No OpenBin AI findings have been generated by this application.")
    else:
        data=scan.reviewed_data
        para(f"Tool: {data['tool']} | model/configuration: {data['model']}")
        para('Processing location (reviewer declaration): '+data.get('processing_location','cloud'))
        para(f"Reviewer: {data['reviewer']} | import: {scan.reviewed_at} UTC | importing account: {scan.imported_by}")
        if not data["findings"]:
            para("Reviewer supplied no evidence-supported indicators; this does not establish safety.")
        for item in data["findings"]:
            para(item["title"]+" ["+item["severity"]+"]","Heading3")
            para(item["detail"])
            para("Evidence: "+item["evidence"])
    para("Consent record","Heading2")
    para(f"Version {scan.consent_version}; hash lookup {'accepted' if scan.hash_consent else 'not accepted'}; external OpenBin/code processing {'accepted' if scan.cloud_consent else 'not accepted'}. Current recorded consent choices for this scan.")
    def footer(canvas,doc):
        canvas.setFont("Helvetica",8)
        canvas.setFillColor(colors.HexColor("#667775"))
        canvas.drawString(42,25,"Sentinel Lab | Local workspace | Preliminary assessment")
        canvas.drawRightString(A4[0]-42,25,str(doc.page))
    SimpleDocTemplate(output,pagesize=A4,leftMargin=42,rightMargin=42,topMargin=40,bottomMargin=45,
                      title="Sentinel Lab assessment").build(story,onFirstPage=footer,onLaterPages=footer)
    return output.getvalue()
